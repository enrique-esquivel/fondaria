package dev.fondaria.e2e;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.TimeUnit;
import java.util.regex.Pattern;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.yaml.snakeyaml.Yaml;

/**
 * Guards the public repository against committed secrets (TASK-LOG step 118). Two rules: no tracked
 * file holds a PEM private key -- the local cluster's keys are generated at bootstrap into a
 * gitignored directory -- and the rendered prod overlay carries no Keycloak credential: no realm
 * user with a password or OTP seed, no client secret other than an environment placeholder, and no
 * {@code kind: Secret} at all (production secrets arrive through ExternalSecrets).
 */
class PublicReleaseSecretsGuardTest {

  /** A PEM private key header of any type (RSA, EC, encrypted, PKCS#8). */
  private static final Pattern PRIVATE_KEY_HEADER =
      Pattern.compile("-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----");

  private static final Pattern ENV_PLACEHOLDER = Pattern.compile("\\$\\{[A-Z0-9_]+\\}");

  private static final ObjectMapper MAPPER = new ObjectMapper();

  @Test
  @DisplayName("No tracked file contains a PEM private key")
  void noTrackedFileContainsAPrivateKey() throws Exception {
    Path root = Path.of(RepositoryRoot.path(""));
    String git = findExecutable("git");
    assertThat(git).as("git must be on PATH to list tracked files").isNotNull();

    Process process = new ProcessBuilder(git, "ls-files", "-z").directory(root.toFile()).start();
    String listing = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
    assertThat(process.waitFor(60, TimeUnit.SECONDS)).isTrue();
    assertThat(process.exitValue()).as("git ls-files must succeed").isZero();

    List<String> tracked = List.of(listing.split("\0"));
    assertThat(tracked).as("git ls-files must list the repository").isNotEmpty();

    List<String> offenders = new ArrayList<>();
    for (String file : tracked) {
      Path path = root.resolve(file);
      // A tracked file deleted in the working tree (not yet committed) has nothing to scan.
      if (!file.isEmpty() && Files.isRegularFile(path) && containsPrivateKey(path)) {
        offenders.add(file);
      }
    }
    assertThat(offenders)
        .as(
            "private keys must never be committed -- local ones are generated by "
                + "infrastructure/k8s/bootstrap/local-secrets.sh into a gitignored directory")
        .isEmpty();
  }

  @Test
  @DisplayName("The private-key detector recognises PEM key headers and ignores certificates")
  void detectorRecognisesPrivateKeyHeaders() {
    String dashes = "-----";
    assertThat(PRIVATE_KEY_HEADER.matcher(dashes + "BEGIN PRIVATE KEY" + dashes).find()).isTrue();
    assertThat(PRIVATE_KEY_HEADER.matcher(dashes + "BEGIN EC PRIVATE KEY" + dashes).find())
        .isTrue();
    assertThat(PRIVATE_KEY_HEADER.matcher(dashes + "BEGIN RSA PRIVATE KEY" + dashes).find())
        .isTrue();
    assertThat(PRIVATE_KEY_HEADER.matcher(dashes + "BEGIN ENCRYPTED PRIVATE KEY" + dashes).find())
        .isTrue();
    assertThat(PRIVATE_KEY_HEADER.matcher(dashes + "BEGIN CERTIFICATE" + dashes).find()).isFalse();
  }

  @Test
  @DisplayName("The rendered prod overlay carries no Keycloak user credential or client secret")
  void prodOverlayCarriesNoKeycloakCredentials() throws Exception {
    List<Map<String, Object>> docs = renderOverlay("prod");

    assertThat(docs)
        .as("prod declares no Secret -- every one is an ExternalSecret")
        .noneMatch(d -> "Secret".equals(d.get("kind")));

    List<JsonNode> realms = new ArrayList<>();
    for (Map<String, Object> doc : docs) {
      if (!"ConfigMap".equals(doc.get("kind"))) {
        continue;
      }
      @SuppressWarnings("unchecked")
      Map<String, Object> data = (Map<String, Object>) doc.getOrDefault("data", Map.of());
      for (Map.Entry<String, Object> entry : data.entrySet()) {
        assertThat(entry.getKey())
            .as("no Keycloak users file (<realm>-users-N.json) in prod")
            .doesNotContainPattern("-users-[0-9]+\\.json$");
        if (entry.getKey().endsWith("-realm.json") || entry.getKey().equals("realm.json")) {
          realms.add(MAPPER.readTree((String) entry.getValue()));
        }
      }
    }
    assertThat(realms).as("prod must import exactly one realm").hasSize(1);
    JsonNode realm = realms.get(0);

    for (JsonNode user : realm.path("users")) {
      assertThat(user.has("credentials"))
          .as("prod realm user %s must carry no credentials", user.path("username").asText())
          .isFalse();
    }
    for (JsonNode client : realm.path("clients")) {
      if (client.has("secret")) {
        assertThat(client.path("secret").asText())
            .as(
                "prod client %s's secret must be an environment placeholder",
                client.path("clientId"))
            .matches(ENV_PLACEHOLDER);
      }
    }
  }

  private static boolean containsPrivateKey(Path path) throws Exception {
    // ISO-8859-1 maps every byte to a char, so binary files scan without decoding errors.
    String content = new String(Files.readAllBytes(path), StandardCharsets.ISO_8859_1);
    return PRIVATE_KEY_HEADER.matcher(content).find();
  }

  private static List<Map<String, Object>> renderOverlay(String overlay) throws Exception {
    String kubectl = findExecutable("kubectl");
    assumeTrue(kubectl != null, "kubectl is required to render the overlay");
    Path overlayPath = Path.of(RepositoryRoot.path("infrastructure/k8s/overlays/" + overlay));
    Process process =
        new ProcessBuilder(kubectl, "kustomize", overlayPath.toString())
            .redirectError(ProcessBuilder.Redirect.DISCARD)
            .start();
    String out = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
    assertThat(process.waitFor(120, TimeUnit.SECONDS)).isTrue();
    assertThat(process.exitValue()).as("kubectl kustomize %s must succeed", overlay).isZero();

    List<Map<String, Object>> docs = new ArrayList<>();
    for (Object doc : new Yaml().loadAll(out)) {
      if (doc instanceof Map<?, ?> map) {
        @SuppressWarnings("unchecked")
        Map<String, Object> typed = (Map<String, Object>) map;
        docs.add(typed);
      }
    }
    return docs;
  }

  private static String findExecutable(String name) {
    String path = System.getenv("PATH");
    if (path != null) {
      for (String dir : path.split(File.pathSeparator)) {
        File file = new File(dir, name);
        if (file.canExecute()) {
          return file.getAbsolutePath();
        }
      }
    }
    return null;
  }
}
